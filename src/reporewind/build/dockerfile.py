"""Render the per-task Dockerfile from a recipe and a pin result.

The Dockerfile is a pure function of its inputs: the same recipe, pin result
and lock produce the same bytes, so golden files can check it and the image
tag can be a hash of what goes in. The image:

* starts ``FROM python:X.Y-slim@sha256:...`` (the digest recorded by
  ``reporewind pin``) and copies ``uv`` from a digest-pinned image;
* installs the recipe's Debian packages, then the locked requirements with
  ``uv pip install --require-hashes`` (when the lock has hashes) and
  ``--exclude-newer`` set to the pin's cutoff;
* copies the repository snapshot at the pinned commit (the build context's
  ``src/`` directory, exported with ``git archive``, so no ``.git`` and no
  clone at build time) and installs the project itself with ``--no-deps``;
* drops to an unprivileged user (uid 10001) and runs the recipe's test
  command. Everything the tests import is installed at build time, so the
  container can run with ``--network none``.
"""

from __future__ import annotations

import hashlib
import json
import shlex
from typing import Final

from reporewind.errors import BuildError
from reporewind.pinning.lock import format_timestamp
from reporewind.pinning.pin import PinResult
from reporewind.recipes.model import InstallMode, Recipe, recipe_hash

RENDERER_VERSION: Final = 1
"""Bumped whenever the rendered text changes for the same inputs."""

UV_IMAGE: Final = (
    "ghcr.io/astral-sh/uv:0.11.29"
    "@sha256:eb2843a1e56fd9e30c7276ce1a52cba86e64c7b385f5e3279a0e08e02dd058fc"
)
USER_ID: Final = 10001
USER_NAME: Final = "rewind"
WORKDIR: Final = "/repo"
LOCK_PATH: Final = "/opt/reporewind/requirements.lock"
SCM_VERSION: Final = "0.0.0+reporewind"
"""Version handed to setuptools-scm / hatch-vcs, since the snapshot has no ``.git``."""


def _json_list(argv: tuple[str, ...] | list[str]) -> str:
    return json.dumps(list(argv), ensure_ascii=True)


def _env_value(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def lock_sha256(lock_text: str) -> str:
    """``sha256:<hex>`` of the lock text, as :class:`PinResult` records it."""
    digest = hashlib.sha256(lock_text.encode("utf-8", "surrogateescape")).hexdigest()
    return f"sha256:{digest}"


def check_inputs(recipe: Recipe, pin: PinResult, lock_text: str) -> None:
    """Raise :class:`BuildError` unless recipe and lock are the ones ``pin`` recorded."""
    if recipe_hash(recipe) != pin.recipe_hash:
        raise BuildError(
            f"the recipe for {pin.repo} changed since it was pinned"
            f" ({pin.recipe_hash} -> {recipe_hash(recipe)}); run `reporewind pin` again"
        )
    if lock_sha256(lock_text) != pin.lock_sha256:
        raise BuildError(f"{pin.lock_file} does not match the sha256 recorded in pin.json")


def render_dockerfile(recipe: Recipe, pin: PinResult, lock_text: str) -> str:
    """The Dockerfile for building ``pin.commit`` with ``recipe``; deterministic."""
    check_inputs(recipe, pin, lock_text)
    cutoff = format_timestamp(pin.exclude_newer)
    hashes = "--hash=" in lock_text
    lines = [
        "# syntax=docker/dockerfile:1",
        f"# Generated by reporewind (renderer {RENDERER_VERSION}); do not edit.",
        f"# {pin.repo} at {pin.commit}, recipe {pin.recipe_hash}",
        f"FROM {UV_IMAGE} AS uv",
        "",
        f"FROM {pin.base_image.reference}",
        "LABEL project=reporewind \\",
        f"      org.reporewind.repo={_env_value(str(pin.repo))} \\",
        f"      org.reporewind.commit={pin.commit} \\",
        f"      org.reporewind.recipe={pin.recipe_hash}",
        "ENV PYTHONDONTWRITEBYTECODE=1 \\",
        "    PYTHONUNBUFFERED=1 \\",
        "    PIP_DISABLE_PIP_VERSION_CHECK=1 \\",
        "    UV_NO_CACHE=1 \\",
        "    UV_PYTHON_DOWNLOADS=never \\",
        f"    SETUPTOOLS_SCM_PRETEND_VERSION={SCM_VERSION}",
    ]
    if recipe.system_packages:
        packages = " ".join(recipe.system_packages)
        lines += [
            "RUN apt-get update \\",
            f"    && apt-get install --yes --no-install-recommends {packages} \\",
            "    && rm -rf /var/lib/apt/lists/*",
        ]
    lines += [
        "COPY --from=uv /uv /usr/local/bin/uv",
        f"RUN useradd --create-home --uid {USER_ID} {USER_NAME}",
        f"COPY requirements.lock {LOCK_PATH}",
    ]
    install = ["uv", "pip", "install", "--system", "--exclude-newer", cutoff]
    if hashes:
        install.append("--require-hashes")
    if pin.packages:
        lines.append(f"RUN {shlex.join([*install, '-r', LOCK_PATH])}")
    lines += [
        f"WORKDIR {WORKDIR}",
        f"COPY --chown={USER_ID}:{USER_ID} src/ {WORKDIR}/",
    ]
    lines += [f"RUN {step}" for step in recipe.pre_install]
    project = ["uv", "pip", "install", "--system", "--exclude-newer", cutoff, "--no-deps"]
    if recipe.install is InstallMode.EDITABLE:
        lines.append(f"RUN {shlex.join([*project, '-e', '.'])}")
    elif recipe.install is InstallMode.PACKAGE:
        lines.append(f"RUN {shlex.join([*project, '.'])}")
    if recipe.env:
        env = [f"{key}={_env_value(value)}" for key, value in sorted(recipe.env.items())]
        lines.append("ENV " + " \\\n    ".join(env))
    lines += [
        f"RUN chown -R {USER_ID}:{USER_ID} {WORKDIR}",
        f"USER {USER_ID}:{USER_ID}",
        f"CMD {_json_list(recipe.test_command)}",
    ]
    return "\n".join(lines) + "\n"


